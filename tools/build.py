"""Stamp the version into the app. Run from the music-book folder before every copy/commit/push:
    python3 tools/build.py

Same scheme as the study app: the footer version = VERSION (the number in the VERSION file, e.g. 1.0) plus a short fingerprint of
the sources, so it changes whenever the app does. The same fingerprint also
  - becomes the ?v= number on every script/stylesheet in index.html (so browsers drop their cached copies), and
  - names the offline cache in sw.js (so an installed copy updates).
Running it twice without changing anything leaves every file as it was. Nothing is bundled: the app runs straight from these files
(from file://, or published from the repository root with GitHub Pages).
"""
import glob
import hashlib
import os
import re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(root)

def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()

def write(p, s):
    with open(p, "w", encoding="utf-8", newline="") as f:
        f.write(s)

base = read("VERSION").strip() if os.path.exists("VERSION") else "1.0"

# fingerprint of everything that is the app, ignoring the bits this script writes (version.js, the ?v= numbers, the cache name)
def normalized(p):
    s = read(p)
    if p == "index.html":
        s = re.sub(r"\?v=[0-9a-zA-Z.]+", "?v=X", s)
    elif p == "sw.js":
        s = re.sub(r"const VERSION = '[^']*';", "const VERSION = 'X';", s)
    return s.encode("utf-8")

sources = ["index.html", "sw.js", "manifest.webmanifest"] + sorted(
    glob.glob("css/*.css") + [p for p in glob.glob("js/**/*.js", recursive=True) if os.path.basename(p) != "version.js"])
h = hashlib.sha1()
for p in sources:
    h.update(p.encode()); h.update(normalized(p))
build = h.hexdigest()[:7]
version = "%s (build %s)" % (base, build)

write("js/version.js",
      "/* generated by tools/build.py: do not edit */\n"
      "var APP_VERSION = '%s';\n"
      "(function () {\n"
      "  function show() { Array.prototype.forEach.call(document.querySelectorAll('[data-version]'), function (e) { e.textContent = APP_VERSION; }); }\n"
      "  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', show); else show();\n"
      "})();\n" % version)

html = re.sub(r"\?v=[0-9a-zA-Z.]+", "?v=" + build, read("index.html"))
write("index.html", html)

sw = re.sub(r"const VERSION = '[^']*';", "const VERSION = 'mb-%s';" % build, read("sw.js"))
write("sw.js", sw)

print("Music Book %s: version.js, index.html ?v=%s, sw.js cache mb-%s" % (version, build, build))
